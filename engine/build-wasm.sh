#!/usr/bin/env bash
# Compiles engine/*.cpp to WASM. Slow and deliberately outside the hot reload
# path: run it explicitly via `npm run build:wasm` when engine sources change.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$ROOT/engine/build"
NAM="$ROOT/engine/third_party/NeuralAmpModelerCore"

if [ ! -d "$NAM/NAM" ]; then
  echo "NeuralAmpModelerCore missing at $NAM — the engine needs it to build." >&2
  exit 1
fi
# Every NAM core translation unit; the library's own CMake builds exactly these.
mapfile -t NAM_SRC < <(find "$NAM/NAM" -name '*.cpp' | sort)

# em++, not emcc. emcc links as C rather than C++ for this input set, leaving
# operator new, the typeinfos embind needs, and __cxa_* undefined — it prints
# "Try linking with 'em++' or passing '-sDEFAULT_TO_CXX'" and exits 1. em++ is
# the C++ driver and the idiomatic answer; DEFAULT_TO_CXX is a workaround on
# the C one.
if ! command -v em++ >/dev/null 2>&1; then
  if [ -f "$ROOT/.emsdk/emsdk_env.sh" ]; then
    # shellcheck disable=SC1091
    source "$ROOT/.emsdk/emsdk_env.sh"
  else
    echo "em++ not found and .emsdk/ is missing. Run engine/setup-emsdk.sh first." >&2
    exit 1
  fi
fi

mkdir -p "$OUT_DIR" "$ROOT/public"

em++ \
  "$ROOT/engine/bindings.cpp" \
  "$ROOT/engine/Engine.cpp" \
  "$ROOT/engine/ProcessorChain.cpp" \
  "$ROOT/engine/GateProcessor.cpp" \
  "$ROOT/engine/CabProcessor.cpp" \
  "$ROOT/engine/DelayProcessor.cpp" \
  "$ROOT/engine/ChorusProcessor.cpp" \
  "$ROOT/engine/DriveProcessor.cpp" \
  "$ROOT/engine/ReverbProcessor.cpp" \
  "$ROOT/engine/TremoloProcessor.cpp" \
  "$ROOT/engine/GainProcessor.cpp" \
  "$ROOT/engine/EqProcessor.cpp" \
  "$ROOT/engine/NamProcessor.cpp" \
  "${NAM_SRC[@]}" \
  -o "$OUT_DIR/nam-engine.js" \
  -std=c++20 \
  -I "$NAM" \
  -I "$NAM/Dependencies/eigen" \
  -I "$NAM/Dependencies/nlohmann" \
  -DNAM_SAMPLE_FLOAT \
  -include "$ROOT/engine/nam_json_config.h" \
  -Wno-exceptions \
  -DNAM_ENABLE_A2_FAST \
  -DEIGEN_DONT_PARALLELIZE \
  -O3 -msimd128 \
  -sMODULARIZE=1 \
  -sEXPORT_ES6=1 \
  -sEXPORT_NAME=createNamEngineModule \
  -sENVIRONMENT=web \
  -sALLOW_MEMORY_GROWTH=0 \
  -sINITIAL_MEMORY=201326592 \
  -sEXPORTED_FUNCTIONS='["_engine_process"]' \
  -sEXPORTED_RUNTIME_METHODS='["HEAPF32","HEAPU8"]' \
  -sDISABLE_EXCEPTION_CATCHING=0 \
  -sASSERTIONS=0 \
  -lembind

cp "$OUT_DIR/nam-engine.wasm" "$ROOT/public/nam-engine.wasm"
cp "$OUT_DIR/nam-engine.js" "$ROOT/public/nam-engine.js"

# Emit a type declaration beside the generated glue. TypeScript resolves a
# sibling .d.ts ahead of the .js, so the worklet imports the factory with real
# types and no suppression comment. A hand-written @ts-expect-error there is
# fragile in both directions: it hides real type errors, and if TS ever stops
# erroring on that line the suppression itself becomes the error.
cat > "$OUT_DIR/nam-engine.d.ts" <<'EOS'
// Generated by engine/build-wasm.sh. Do not edit.
//
// The embind surface from engine/bindings.cpp, plus the two raw members the
// hot path uses. Keep in step with EMSCRIPTEN_BINDINGS and EXPORTED_FUNCTIONS.
export interface NamEngineModule {
  createEngine(): void;
  prepareEngine(sampleRate: number, maxBlockSize: number): void;
  resetEngine(): void;
  /**
   * Start of the 128-frame audio buffer. Processing is IN PLACE, so this
   * returns the SAME address as getOutputPtr() — read and write through one
   * pair of views and do not copy between them.
   */
  getInputPtr(): number;
  /** Deliberately the same address as getInputPtr(). See above. */
  getOutputPtr(): number;
  getParamPtr(): number;
  getMaxBlockSize(): number;
  getParamCount(): number;
  /** Engine::kEqBaseIndex — must equal PARAM_INDEX.eqBase in params.ts. */
  getEqBaseIndex(): number;
  /** Engine::kOutputVolumeIndex — must equal PARAM_INDEX.outputVolume in params.ts. */
  getOutputVolumeIndex(): number;
  /** Engine::kSlotBaseIndex — must equal PARAM_INDEX.slotBase in params.ts. */
  getSlotBaseIndex(): number;
  /** Engine::kParamsPerSlot — must equal PARAMS_PER_SLOT in params.ts. */
  getParamsPerSlot(): number;
  /** Engine::kEqLevelIndex — must equal PARAM_INDEX.eqLevel in params.ts. */
  getEqLevelIndex(): number;
  /** Engine::kGateThresholdIndex — must equal PARAM_INDEX.gateThreshold in params.ts. */
  getGateThresholdIndex(): number;
  /** Engine::kCabLevelIndex — must equal PARAM_INDEX.cabLevel in params.ts. */
  getCabLevelIndex(): number;
  /** Engine::kNamCount — must equal NAM_SLOT_COUNT in params.ts. */
  getNamCount(): number;
  /**
   * Start of the model staging buffer. Copy bytes here, then call
   * loadNamModel(). Derived ONCE, like every other heap pointer.
   */
  getModelStagingPtr(): number;
  /** Engine::kMaxModelBytes — the largest payload loadNamModel() accepts. */
  getMaxModelBytes(): number;
  /** Builds slot `slot`'s model from the first `byteLength` staged bytes. */
  loadNamModel(slot: number, byteLength: number): boolean;
  /** Flips Processor::enabled on a NAM stage. */
  setNamEnabled(slot: number, enabled: boolean): void;
  /**
   * Start of the cab's IR staging buffer (Float32, getMaxIrTaps() entries).
   * Copy taps here, then call loadCabIr(). Derived ONCE, like every other heap pointer.
   */
  getIrStagingPtr(): number;
  /** Engine::kMaxCabTaps — the most taps loadCabIr() accepts. */
  getMaxIrTaps(): number;
  /** Commits the first `length` staged taps as the cab's IR. False if rejected. */
  loadCabIr(length: number): boolean;
  /** Flips Processor::enabled on a named core stage. `stage` is an Engine::Stage value. */
  setStageEnabled(stage: number, enabled: boolean): void;
  /**
   * The POST effects, first to last, as Engine::Stage values: a permutation of
   * Chorus (4), Tremolo (7), Delay (3) and Reverb (6). Anything else changes nothing.
   */
  setPostOrder(first: number, second: number, third: number, fourth: number): void;
  /** Trails: closed, an enabled reverb lets its tail ring out and passes the dry. */
  setReverbInput(open: boolean): void;
  /** View over the whole WASM heap. Derive subarrays once; never re-derive. */
  HEAPF32: Float32Array;
  /** Byte view over the whole WASM heap. Derive subarrays once; never re-derive. */
  HEAPU8: Uint8Array;
  /** Raw export, deliberately not an embind function: this is the hot path. */
  _engine_process(numFrames: number): void;
}

export interface NamEngineModuleOptions {
  /**
   * Emscripten's instantiation hook, not the raw bytes. AudioWorkletGlobalScope
   * has no `fetch` and no `URL`, and the glue's default loader calls
   * `new URL("nam-engine.wasm", import.meta.url)` before it ever looks at a
   * supplied binary — so handing over `wasmBinary` alone is not enough; the
   * glue throws `ReferenceError: URL is not defined` before it gets there.
   * `instantiateWasm` is checked first and short-circuits that path: the
   * caller instantiates the bytes itself (typically a plain
   * `WebAssembly.instantiate`) and hands the resulting instance back via
   * `successCallback`.
   */
  instantiateWasm(
    imports: WebAssembly.Imports,
    successCallback: (instance: WebAssembly.Instance) => void,
  ): WebAssembly.Exports;
}

declare const createNamEngineModule: (
  options: NamEngineModuleOptions,
) => Promise<NamEngineModule>;

export default createNamEngineModule;
EOS

echo "Built $(du -h "$ROOT/public/nam-engine.wasm" | cut -f1) of WASM into public/nam-engine.wasm"
echo "Wrote $OUT_DIR/nam-engine.d.ts"

# The worklet bundle inlines the glue emitted above, so it MUST be rebuilt here.
# Regenerating the glue without rebundling leaves the browser loading a new .wasm
# against an old glue: their embind registrations disagree and the module dies at
# instantiation with "TypeError: invalid integer width (N)". The input meter keeps
# working (it taps ahead of the worklet), so it looks like anything but a build
# problem.
( cd "$ROOT" && npx vite build --config vite.worklet.config.ts )
