/// <reference types="@types/audioworklet" />
import {
  CORE_PARAMS,
  CORE_PARAM_ORDER,
  NAM_SLOT_COUNT,
  PARAM_COUNT,
  PARAM_INDEX,
  PARAM_ORDER,
  PARAMS_PER_SLOT,
} from './params';
import { isPostOrder, type EngineCommand, type StageId } from './engineMessages';

// Not declared by the installed @types/audioworklet@0.0.100 — that package
// types AudioWorkletProcessorConstructor's `new` as `(options: any)` and has
// no `parameterDescriptors`/AudioParamDescriptor at all (checked: neither
// name appears in its index.d.ts). Declared locally, matching the Web Audio
// API shape (AutomationRate itself does come from the DOM lib already in
// scope), until the package catches up.
interface AudioParamDescriptor {
  name: string;
  automationRate?: AutomationRate;
  minValue?: number;
  maxValue?: number;
  defaultValue?: number;
}

// Generated by engine/build-wasm.sh, which emits nam-engine.d.ts beside the
// .js so this import carries real types. If it fails to resolve, the engine
// has not been built: run `npm run build:wasm`.
import createNamEngineModule, {
  type NamEngineModule,
} from '../../engine/build/nam-engine.js';

const QUANTUM = 128;

// Mirrors enum class Engine::Stage in engine/Engine.h — the one place the
// string ids become the engine's numeric ones.
const STAGE_IDS: Record<StageId, number> = { gate: 0, eq: 1, cab: 2, delay: 3, chorus: 4, drive: 5, reverb: 6, tremolo: 7 };

class NamEngineProcessor extends AudioWorkletProcessor {
  static get parameterDescriptors(): AudioParamDescriptor[] {
    // The pool is fixed at class-definition time. Phase 3's effects index into
    // the slot parameters; they cannot be added later.
    return PARAM_ORDER.map((id) => {
      const core = (CORE_PARAMS as Record<string, { min: number; max: number; default: number }>)[id];
      return core
        ? {
            name: id,
            defaultValue: core.default,
            minValue: core.min,
            maxValue: core.max,
            automationRate: 'k-rate' as const,
          }
        : {
            name: id,
            defaultValue: 0,
            minValue: -1e6,
            maxValue: 1e6,
            automationRate: 'k-rate' as const,
          };
    });
  }

  private module: NamEngineModule | null = null;
  private heapIn: Float32Array | null = null;
  private heapOut: Float32Array | null = null;
  private heapParams: Float32Array | null = null;
  private heapModel: Uint8Array | null = null;
  private heapIr: Float32Array | null = null;
  private silence = new Float32Array(QUANTUM);

  constructor(options: AudioWorkletNodeOptions) {
    super();

    const wasmBinary = (options.processorOptions as { wasmBinary?: ArrayBuffer })?.wasmBinary;
    if (!wasmBinary) {
      this.port.postMessage({ type: 'error', message: 'no wasmBinary in processorOptions' });
      return;
    }

    createNamEngineModule({
      // Not `{ wasmBinary }`. See NamEngineModuleOptions in the generated
      // .d.ts: the glue's loader reaches for `new URL(...)` before it reads any
      // bytes, and AudioWorkletGlobalScope has no `URL`. This hook is checked
      // first and short-circuits that path. An arrow function so `this` is
      // still the processor.
      instantiateWasm: (imports, successCallback) => {
        WebAssembly.instantiate(wasmBinary, imports)
          .then((result) => successCallback(result.instance))
          .catch((err: unknown) => {
            this.port.postMessage({ type: 'error', message: `instantiate: ${String(err)}` });
          });
        return {};
      },
    })
      .then((mod: NamEngineModule) => {
        mod.createEngine();
        mod.prepareEngine(sampleRate, QUANTUM);

        if (mod.getParamCount() !== PARAM_COUNT) {
          this.port.postMessage({
            type: 'error',
            message: `param count mismatch: engine ${mod.getParamCount()}, ts ${PARAM_COUNT}`,
          });
          return;
        }

        // getParamCount() above only catches a length mismatch, not a
        // reordering: a coordinated edit to Engine.h and params.ts could keep
        // the count (and every existing test) green while a knob quietly
        // drives the wrong DSP parameter. Each entry below compares one fixed
        // point in the parameter layout between the two sides, at the one
        // point where the C++ and TS sides of the contract can actually be
        // held up against each other.
        const layoutChecks: Array<[string, number, number]> = [
          ['eqBase', mod.getEqBaseIndex(), PARAM_INDEX.eqBase],
          ['eqLevel', mod.getEqLevelIndex(), PARAM_INDEX.eqLevel],
          ['outputVolume', mod.getOutputVolumeIndex(), PARAM_INDEX.outputVolume],
          ['gateThreshold', mod.getGateThresholdIndex(), PARAM_INDEX.gateThreshold],
          ['cabLevel', mod.getCabLevelIndex(), PARAM_INDEX.cabLevel],
          ['slotBase', mod.getSlotBaseIndex(), PARAM_INDEX.slotBase],
          ['namCount', mod.getNamCount(), NAM_SLOT_COUNT],
          ['paramsPerSlot', mod.getParamsPerSlot(), PARAMS_PER_SLOT],
        ];
        for (const [name, engineIndex, tsIndex] of layoutChecks) {
          if (engineIndex !== tsIndex) {
            this.port.postMessage({
              type: 'error',
              message: `param layout mismatch at ${name}: engine ${engineIndex}, ts ${tsIndex}`,
            });
            return;
          }
        }

        // Same class of check as the one above, for the other number the heap
        // views are sized by. The engine returns a compile-time constant here,
        // so this can only fire if someone changes kMaxBlockSize — and if they
        // do, the failure without this guard is `heapIn.set()` throwing inside
        // process(), on the audio thread, every quantum. Catch it once, here.
        const maxBlock = mod.getMaxBlockSize();
        if (maxBlock !== QUANTUM) {
          this.port.postMessage({
            type: 'error',
            message: `block size mismatch: engine ${maxBlock}, render quantum ${QUANTUM}`,
          });
          return;
        }

        // Derived ONCE. The module is built with ALLOW_MEMORY_GROWTH=0 precisely
        // so these views stay valid for the life of the worklet.
        const inputPtr = mod.getInputPtr();
        const outputPtr = mod.getOutputPtr();
        const paramPtr = mod.getParamPtr();

        this.heapIn = mod.HEAPF32.subarray(inputPtr >> 2, (inputPtr >> 2) + maxBlock);
        this.heapOut = mod.HEAPF32.subarray(outputPtr >> 2, (outputPtr >> 2) + maxBlock);
        this.heapParams = mod.HEAPF32.subarray(paramPtr >> 2, (paramPtr >> 2) + PARAM_COUNT);

        const stagingPtr = mod.getModelStagingPtr();
        this.heapModel = mod.HEAPU8.subarray(stagingPtr, stagingPtr + mod.getMaxModelBytes());
        const irPtr = mod.getIrStagingPtr();
        this.heapIr = mod.HEAPF32.subarray(irPtr >> 2, (irPtr >> 2) + mod.getMaxIrTaps());

        this.module = mod;

        // Assigning onmessage starts the port. Handlers run on the audio
        // thread between quanta: copy bytes, swap a pointer, nothing heavier.
        this.port.onmessage = (event: MessageEvent) => {
          this.handleCommand(event.data as EngineCommand);
        };

        this.port.postMessage({
          type: 'ready',
          sampleRate,
          maxBlock,
          maxModelBytes: mod.getMaxModelBytes(),
          maxIrTaps: mod.getMaxIrTaps(),
        });
      })
      .catch((err: unknown) => {
        this.port.postMessage({ type: 'error', message: String(err) });
      });
  }

  // Runs on the audio thread between quanta: copy bytes, swap a pointer,
  // nothing heavier. Every 'loadModel' must produce exactly one 'modelLoaded'
  // reply — the panel's FIFO ack counter (sentCountRef/ackCountRef in
  // NamLoaderPanel) permanently desyncs the moment a send goes unacknowledged,
  // silently swallowing every later rejection too. So the not-ready case and
  // any throw inside the handler both report ok:false instead of returning
  // silently. 'setEnabled' has no such counter and stays ack-free.
  private handleCommand(command: EngineCommand): void {
    switch (command.type) {
      case 'setEnabled': {
        this.module?.setNamEnabled(command.slot, command.enabled);
        return;
      }
      case 'setStageEnabled': {
        this.module?.setStageEnabled(STAGE_IDS[command.stage], command.enabled);
        return;
      }
      case 'setPostOrder': {
        // Only a permutation of the POST effects reaches the engine; anything
        // else a message carries changes nothing rather than arriving as NaN.
        if (isPostOrder(command.order)) {
          const [first, second, third, fourth] = command.order;
          this.module?.setPostOrder(STAGE_IDS[first], STAGE_IDS[second], STAGE_IDS[third], STAGE_IDS[fourth]);
        }
        return;
      }
      case 'setReverbInput': {
        this.module?.setReverbInput(command.open === true);
        return;
      }
      case 'loadModel': {
        const mod = this.module;
        const staging = this.heapModel;
        if (mod === null || staging === null) {
          this.port.postMessage({
            type: 'modelLoaded',
            slot: command.slot,
            ok: false,
            message: 'the engine is not ready yet',
          });
          return;
        }

        try {
          const bytes = new Uint8Array(command.bytes);
          if (bytes.length === 0 || bytes.length > staging.length) {
            this.port.postMessage({
              type: 'modelLoaded',
              slot: command.slot,
              ok: false,
              message: `model is ${bytes.length} bytes; the limit is ${staging.length}`,
            });
            return;
          }

          staging.set(bytes);
          const ok = mod.loadNamModel(command.slot, bytes.length);
          this.port.postMessage({
            type: 'modelLoaded',
            slot: command.slot,
            ok,
            message: ok ? '' : `the engine rejected the model for slot ${command.slot}`,
          });
        } catch (err: unknown) {
          // Not currently reachable (parsing is just a length check today),
          // but real inference will add real parsing here, and letting a
          // throw escape onto the audio thread would both crash the worklet
          // and leave this ack unsent.
          this.port.postMessage({
            type: 'modelLoaded',
            slot: command.slot,
            ok: false,
            message: `loadModel threw: ${String(err)}`,
          });
        }
        return;
      }
      case 'loadIr': {
        // Every 'loadIr' must produce exactly one 'irLoaded' reply, for the
        // same reason as 'loadModel': the panel matches replies to sends
        // first-in first-out, so one unanswered send desyncs every later one.
        const mod = this.module;
        const staging = this.heapIr;
        if (mod === null || staging === null) {
          this.replyIr(false, 'the engine is not ready yet');
          return;
        }
        try {
          if (command.bytes.byteLength % 4 !== 0) {
            this.replyIr(false, `IR is ${command.bytes.byteLength} bytes, not a whole number of floats`);
            return;
          }
          const taps = new Float32Array(command.bytes);
          if (taps.length === 0 || taps.length > staging.length) {
            this.replyIr(false, `IR is ${taps.length} taps; the limit is ${staging.length}`);
            return;
          }
          staging.set(taps);
          const ok = mod.loadCabIr(taps.length);
          this.replyIr(ok, ok ? '' : 'the engine rejected the IR (a non-finite tap)');
        } catch (err: unknown) {
          this.replyIr(false, `loadIr threw: ${String(err)}`);
        }
        return;
      }
      default: {
        // Exhaustiveness check: a future third EngineCommand variant fails to
        // compile here instead of being silently dropped at runtime.
        const unreachable: never = command;
        return unreachable;
      }
    }
  }

  private replyIr(ok: boolean, message: string): void {
    this.port.postMessage({ type: 'irLoaded', ok, message });
  }

  process(
    inputs: Float32Array[][],
    outputs: Float32Array[][],
    parameters: Record<string, Float32Array>,
  ): boolean {
    const output = outputs[0];
    if (!output || output.length === 0) return true;

    const mod = this.module;
    if (mod === null || this.heapIn === null || this.heapOut === null || this.heapParams === null) {
      // Still instantiating: emit silence rather than noise.
      for (let ch = 0; ch < output.length; ch++) output[ch].set(this.silence);
      return true;
    }

    // 1. Input into the WASM heap. Guitar is mono; a disconnected input arrives
    //    as an empty array, which is silence, not an error.
    const inputChannel = inputs[0]?.[0];
    if (inputChannel && inputChannel.length === QUANTUM) {
      this.heapIn.set(inputChannel);
    } else {
      this.heapIn.fill(0);
    }

    // 2. Current k-rate values into the param block. k-rate arrays are length 1
    //    unless an automation is running, in which case index 0 is still the
    //    value for this quantum.
    const params = this.heapParams;
    for (let i = 0; i < PARAM_COUNT; i++) {
      const values = parameters[PARAM_ORDER[i]];
      if (values !== undefined) params[i] = values[0];
    }

    // 3. Run the chain.
    mod._engine_process(QUANTUM);

    // 4. Out, duplicated to both channels. One mono signal processed once.
    for (let ch = 0; ch < output.length; ch++) output[ch].set(this.heapOut);

    return true;
  }
}

registerProcessor('nam-engine', NamEngineProcessor);

// CORE_PARAM_ORDER is imported so a change to the core list is a type error here
// rather than a silent index shift against the engine.
void CORE_PARAM_ORDER;
